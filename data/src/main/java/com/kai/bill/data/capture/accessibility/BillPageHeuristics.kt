package com.kai.bill.data.capture.accessibility

/**
 * 「这一屏是不是**账单详情页**」的判定 —— 纯函数，不依赖任何 Android 类型。
 *
 * 为什么要把这段规则从无障碍服务里抽出来：它**极易误判**，而每一次误判都会凭空建一笔错账
 * 并弹卡（真机复现：支付宝「小荷包」账户页的 `总金额 564.18` 被当成一笔 ¥564.18 的交易）。
 * 判定完全由页面文本决定，抽成独立对象后就能拿**真实页面文本**写回归测试，
 * 不必每次都在真机上反复试错。
 *
 * 判定口径：**同时**满足
 * 1. 命中至少一个 [BILL_DETAIL_MARKERS]（只有「某一笔交易」的详情页才有的字段）；
 * 2. 不含任何 [NON_BILL_MARKERS]（聊天 / 主界面 / 账单列表 / 账户资产页的特征词）。
 */
object BillPageHeuristics {

    /**
     * 账单详情页专有字段：聊天 / 主界面 / 账单列表 / 账户页都不会出现这些词。
     *
     * 刻意**不收**「支付 / 账单 / 金额」这类泛滥词 —— 它们到处都是，
     * 早期按这类词收录时把聊天内容、账户余额都当成了交易。
     */
    private val BILL_DETAIL_MARKERS = listOf(
        "支付时间", "交易时间", "转账时间",
        "交易单号", "商户单号", "转账单号",
        "商户全称", "收单机构", "商户名称", "收款方备注",
        "账单服务", "在此商户的交易", "对订单有疑惑"
    )

    /**
     * 「不是账单详情页」的特征词：出现即否决。
     *
     * - 聊天 / 主界面 / 账单列表：微信的浮窗、通讯录、聊天信息、正在加载…；
     * - **账户 / 资产页**：支付宝「小荷包」等会把「总金额 / 收益」摆在显眼处，
     *   真机上曾被判成账单详情页，把余额记成一笔交易。
     */
    private val NON_BILL_MARKERS = listOf(
        "浮窗", "通讯录", "切换到发消息", "聊天信息", "文件传输助手", "正在加载", "视频号",
        // 账户 / 资产 / 统计明细页：真机复现（2026-09-19）—— 支付宝「小荷包」页的明细里
        // 有一行「退款-商户单号 XP…」，命中了「商户单号」这个详情字段，整页被判成账单详情页，
        // 又把「总金额 564.18」记成了一笔 ¥564.18 的交易。这些词能把它干净挡下。
        "总金额", "定期金额", "累计收益", "邀请他人加入", "查看权益", "月支出", "月收入", "统计明细"
    )

    /**
     * @param text 已归一化为单行的页面文本（见 [PageTextExtractor]）
     * @return true 表示可以按「某一笔交易的详情」来处理
     */
    fun isBillDetail(text: String): Boolean =
        NON_BILL_MARKERS.none { text.contains(it) } && BILL_DETAIL_MARKERS.any { text.contains(it) }
}
