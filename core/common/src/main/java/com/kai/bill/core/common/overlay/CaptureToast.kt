package com.kai.bill.core.common.overlay

/**
 * 底部「轻提示」出口 —— 与确认卡片互补：
 * **卡片是「有事要你决定」，轻提示是「告诉你结果」**。
 *
 * 存在理由：识别链路上有一批「有结论、但不需要你操作」的结果，例如
 * 「这笔账单已记录，无需重复记录」。以前这些结果只写进诊断，屏幕上一片安静，
 * 用户会怀疑「到底识别到了没有」，于是反复打开同一个页面去看 ——
 * 商业产品（小黑记账）正是在同样的位置弹一条这样的提示。
 *
 * 实现约定：
 * - **不抢焦点、不拦截触摸**：用户必须能继续操作原来的 App；
 * - 到点自动消失；新消息顶掉旧消息（同一时刻只留一条）。
 */
interface CaptureToast {

    /**
     * 显示一条短暂提示。
     *
     * 实现**不得抛异常** —— 提示是「更好」，不是「必须」，不能因为弹不出提示就中断采集链路。
     */
    suspend fun show(message: String)
}
