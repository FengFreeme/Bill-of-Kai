package com.kai.bill.core.common.overlay

/**
 * 这张确认卡片代表的是「补分类」还是「新建一笔」。
 *
 * 两者对用户的意义**完全不同**，文案必须区分，否则用户无法判断要不要动手核对：
 * - [CREATED]：本来没有这笔账，是识别结果**凭空补了一笔** —— 用户最需要知道；
 * - [ENRICHED]：账已经有了（多半来自通知），只是**分类被修正**了 —— 用户只需知道改成了什么。
 */
enum class ReviewKind {

    /** 无账可配，由识别结果新建了一笔 */
    CREATED,

    /** 命中已有账单，补全 / 修正了它的分类 */
    ENRICHED
}
