package com.kai.bill.domain.model

/**
 * 一条通知没能直接记账、需要人工确认的原因。
 *
 * 为什么要单独建模而不是复用「未命中」一个值：待确认列表里必须能向用户解释
 * **为什么把你叫过来**（「因为『转出成功』，这笔可能只是账户互转」），
 * 同时它决定建议值的默认口径 —— 例如 [GIFT] 与 [SELF_TRANSFER] 的建议都是「不计入统计」，
 * 而 [DIRECTION_UNKNOWN] 连方向都给不出来，只能给空建议。
 *
 * 与 [BillType] 的关系：本枚举只描述「不确定什么」，不描述「最终算作什么」——
 * 用户确认后落库的仍然是 [BillType] 三值之一，两者不可混用。
 */
enum class PendingReason {

    /** 完全没命中任何方向词：连是支出还是收入都判不出来 */
    DIRECTION_UNKNOWN,

    /** 自己的钱搬家：转出 / 提现 / 取现 / 代付 */
    SELF_TRANSFER,

    /** 红包：收 / 发、算不算人情往来因人而异 */
    GIFT,

    /**
     * 泛化入账：入账 / 转入 / 存入 / 到账。
     *
     * 与「工资 / 报销 / 退款」这类具体收入词分开处理的原因：泛化词无法区分
     * 「别人真的给了我钱」与「我把钱从自己的另一个账户挪过来」，若默认记为收入会虚增统计。
     */
    GENERIC_INBOUND
}
